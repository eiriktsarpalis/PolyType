using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;
using PolyType.FastPathJson.SourceGenerator.Helpers;
using PolyType.FastPathJson.SourceGenerator.Model;
using PolyType.Roslyn;
using PolyType.Roslyn.Helpers;
using System.Text;

namespace PolyType.FastPathJson.SourceGenerator;

internal static partial class SourceFormatter
{
    private const string Writer = "global::System.Text.Json.Utf8JsonWriter";
    private const string Reader = "global::System.Text.Json.Utf8JsonReader";
    private const string Token = "global::System.Text.Json.JsonTokenType.";
    private const string JsonException = "global::System.Text.Json.JsonException";
    private const string Contract = "global::PolyType.FastPathJson.IJsonSerializable";
    private const string Shared = "global::PolyType.FastPathJson.SerializationHelpers";

    public static void Generate(SourceProductionContext context, GenerationModel model)
    {
        if (model.Roots.Length == 0)
        {
            return;
        }

        HashSet<string> hierarchyCaseTypes = new(
            model.Converters.OfType<ObjectConverterModel>().SelectMany(m => m.UnionCases).Select(c => c.Type.Name),
            StringComparer.Ordinal);
        foreach (ConverterModel converter in model.Converters)
        {
            context.CancellationToken.ThrowIfCancellationRequested();
            if (converter.Type.Witness is not null)
            {
                continue;
            }

            string name = converter.Type.Converter.Substring(ScalarTypes.GeneratedPrefix.Length);
            context.AddSource($"FastPathJson.Converters.{name}.g.cs",
                WriteConverter(converter, name, hierarchyCaseTypes.Contains(converter.Type.Name)));
        }

        Dictionary<string, ConverterModel> converters = model.Converters.ToDictionary(c => c.Type.Name, StringComparer.Ordinal);
        foreach (RootModel root in model.Roots)
        {
            context.CancellationToken.ThrowIfCancellationRequested();
            context.AddSource($"FastPathJson.{root.SourceIdentifier}.g.cs", SourceText.From(WriteRoot(root, converters, hierarchyCaseTypes), Encoding.UTF8));
        }
    }

    private static void StartConverterSourceFile(SourceWriter writer)
    {
        writer.WriteLine("""
            // <auto-generated/>

            #nullable enable

            namespace PolyType.FastPathJson.Generated;

            internal static partial class GeneratedJsonConverters
            {
            """);
        writer.Indentation++;
    }

    private static SourceText WriteConverter(ConverterModel converter, string name, bool needsPropertyWriter)
    {
        using SourceWriter writer = new();
        StartConverterSourceFile(writer);
        writer.WriteLine($"internal sealed class {name} : {Contract}<{converter.Type.Name}>");
        writer.WriteLine('{');
        writer.Indentation++;
        writer.WriteLine($"private {name}() {{ }}");
        writer.WriteLine();
        WriteConverterMembers(writer, converter, needsPropertyWriter);
        writer.Indentation--;
        writer.WriteLine('}');
        writer.Indentation--;
        writer.WriteLine('}');
        return writer.ToSourceText();
    }

    private static void WriteConverterMembers(SourceWriter writer, ConverterModel converter, bool needsPropertyWriter)
    {
        switch (converter)
        {
            case ObjectConverterModel obj:
                WriteObjectConverter(writer, obj, needsPropertyWriter);
                break;
            case EnumerableConverterModel enumerable:
                WriteEnumerableConverter(writer, enumerable);
                break;
            case DictionaryConverterModel dictionary:
                WriteDictionaryConverter(writer, dictionary);
                break;
            case ArrayConverterModel array:
                WriteArrayConverter(writer, array);
                break;
            case BuiltInCollectionConverterModel collection:
                WriteBuiltInCollectionConverter(writer, collection);
                break;
        }
    }

    private static string WriteRoot(RootModel model, Dictionary<string, ConverterModel> converters, HashSet<string> hierarchyCaseTypes)
    {
        TypeRef type = model.Type;
        using SourceWriter writer = new();
        writer.WriteLine("// <auto-generated/>");
        writer.WriteLine("// Attribute type arguments do not encode nullable-reference annotations.");
        writer.WriteLine("#nullable disable");
        writer.WriteLine();
        if (model.Namespace is { } ns)
        {
            writer.WriteLine($"namespace {ns};");
            writer.WriteLine();
        }

        for (int i = 0; i < model.Declarations.Length; i++)
        {
            string interfaces = i == model.Declarations.Length - 1
                ? $" : {Contract}<{type.Name}>"
                : "";
            writer.WriteLine(model.Declarations[i] + interfaces);
            writer.WriteLine('{');
            writer.Indentation++;
        }

        writer.WriteLine("#nullable enable annotations", disableIndentation: true);
        writer.WriteLine();
        if (converters.TryGetValue(type.Name, out ConverterModel? converter))
        {
            WriteConverterMembers(writer, converter, hierarchyCaseTypes.Contains(type.Name));
        }
        else
        {
            writer.WriteLine($"static void {Contract}<{type.Name}>.Write({Writer} writer, {type.Name} value) =>");
            writer.Indentation++;
            writer.WriteLine($"{Shared}.Write<{type.Name}, {type.Converter}>(writer, value);");
            writer.Indentation--;
            writer.WriteLine();
            writer.WriteLine($"static {type.Name} {Contract}<{type.Name}>.Read(ref {Reader} reader) =>");
            writer.Indentation++;
            writer.WriteLine($"{FormatRead(type with { Witness = null })};");
            writer.Indentation--;
            if (type.SupportsPropertyNames)
            {
                writer.WriteLine();
                writer.WriteLine($"static void {Contract}<{type.Name}>.WriteAsPropertyName({Writer} writer, {type.Name} value) =>");
                writer.Indentation++;
                writer.WriteLine($"{Shared}.WriteKey<{type.Name}, {type.Converter}>(writer, value);");
                writer.Indentation--;
                writer.WriteLine();
                writer.WriteLine($"static {type.Name} {Contract}<{type.Name}>.ReadAsPropertyName(ref {Reader} reader) =>");
                writer.Indentation++;
                writer.WriteLine($"{Shared}.ReadKey<{type.Name}, {type.Converter}>(ref reader);");
                writer.Indentation--;
            }
        }

        for (int i = 0; i < model.Declarations.Length; i++)
        {
            writer.Indentation--;
            writer.WriteLine('}');
        }

        return writer.ToString();
    }

    private static void WriteNullGuard(SourceWriter writer, TypeRef type, bool reading)
    {
        if (type.IsValueType)
        {
            return;
        }

        writer.WriteLine(reading
            ? $$"""
                if (reader.TokenType is {{Token}}Null)
                {
                    return null;
                }
                """
            : """
                if (value is null)
                {
                    writer.WriteNullValue();
                    return;
                }
                """);
        writer.WriteLine();
    }

    private static string Literal(string text) => SymbolDisplay.FormatLiteral(text, quote: true);

    private static string Literal(char value) => SymbolDisplay.FormatLiteral(value, quote: true);

    private static string GetConverterIdentifier(TypeRef type) => type.Converter.Substring(ScalarTypes.GeneratedPrefix.Length);

    private static string FormatWrite(TypeRef type, string value) =>
        $"{Shared}.Write<{type.Name}, {type.WitnessType}>(writer, {value})";

    private static string? GetPrimitiveWriteMethod(TypeRef type) =>
        type.Converter switch
        {
            ScalarTypes.Prefix + "BooleanConverter" => "WriteBoolean",
            ScalarTypes.Prefix + "SByteConverter" or ScalarTypes.Prefix + "Int16Converter" or
            ScalarTypes.Prefix + "Int32Converter" or ScalarTypes.Prefix + "Int64Converter" or
            ScalarTypes.Prefix + "ByteConverter" or ScalarTypes.Prefix + "UInt16Converter" or
            ScalarTypes.Prefix + "UInt32Converter" or ScalarTypes.Prefix + "UInt64Converter" or
            ScalarTypes.Prefix + "SingleConverter" or ScalarTypes.Prefix + "DoubleConverter" or
            ScalarTypes.Prefix + "DecimalConverter" => "WriteNumber",
            ScalarTypes.Prefix + "StringConverter" or ScalarTypes.Prefix + "GuidConverter" or
            ScalarTypes.Prefix + "DateTimeConverter" or ScalarTypes.Prefix + "DateTimeOffsetConverter" => "WriteString",
            _ => null,
        };

    private static string? FormatFusedPropertyWrite(TypeRef type, string name, string value)
    {
        if (GetPrimitiveWriteMethod(type) is { } method)
        {
            return $"writer.{method}({name}, {value})";
        }

        return type.Converter == ScalarTypes.Prefix + "UriConverter"
            ? $"writer.WriteString({name}, ({value})?.OriginalString)"
            : null;
    }

    private static string? FormatFusedDictionaryEntry(TypeRef key, TypeRef value) =>
        key.Converter == ScalarTypes.Prefix + "StringConverter"
            ? FormatFusedPropertyWrite(value, "entry.Key", "entry.Value")
            : null;

    private static string FormatBuiltInKeyWrite(TypeRef type, string value) =>
        type.Converter == ScalarTypes.Prefix + "StringConverter"
            ? $"writer.WritePropertyName({value})"
            : IsScalarConverter(type)
            ? $"{type.Converter}.WriteAsPropertyName(writer, {value})"
            : $"{Shared}.WriteKey<{type.Name}, {type.WitnessType}>(writer, {value})";

    private static bool IsScalarConverter(TypeRef type) =>
        type.Converter.StartsWith(ScalarTypes.Prefix, StringComparison.Ordinal) &&
        (type.SupportsPropertyNames || type.Converter.IndexOf('<') < 0);

    private static string FormatRead(TypeRef type, string reader = "reader") =>
        $"{Shared}.Read<{type.Name}, {type.ReadWitnessType}>(ref {reader})";
}
